function createYalaTouristSurveyForm() {
  var form = FormApp.create('แบบสำรวจข้อมูลนักท่องเที่ยว (วัดคูหาภิมุข อ.เมืองยะลา)');
  // ⚠️ ห้ามรันซ้ำกับฟอร์มที่มี QR แล้ว: จะได้ฟอร์มใหม่ URL ใหม่ (ไฟล์นี้เก็บไว้เป็นเอกสารอ้างอิงให้ตรงกับ docx)
  form.setDescription(
    'สำหรับการพัฒนาระบบแดชบอร์ดสนับสนุนการตัดสินใจของผู้ประกอบการท่องเที่ยว
' +
    'ประกอบการวิจัยเรื่อง การออกแบบและพัฒนาระบบแดชบอร์ดวิเคราะห์ข้อมูลนักท่องเที่ยวเพื่อสนับสนุนการตัดสินใจของผู้ประกอบการท่องเที่ยว กรณีศึกษาพื้นที่นำร่องอำเภอเมืองยะลา จังหวัดยะลา

' +
    'คำชี้แจงและความสมัครใจ: แบบสำรวจฉบับนี้จัดทำขึ้นเพื่อรวบรวมข้อมูลจากผู้มาเยือนวัดคูหาภิมุข (วัดหน้าถ้ำ) ที่มีอายุ 18 ปีบริบูรณ์ขึ้นไป เพื่อนำข้อมูลสรุปในภาพรวมไปแสดงผลบนระบบสารสนเทศ (แดชบอร์ด) สำหรับช่วยให้ผู้ประกอบการในท้องถิ่นวางแผนพัฒนาสินค้าและบริการให้ตรงกับความต้องการของนักท่องเที่ยว โดยไม่เปิดเผยคำตอบรายบุคคล ใช้เวลาตอบประมาณ 3–5 นาที การเข้าร่วมเป็นความสมัครใจ ท่านสามารถไม่เข้าร่วม ยุติการตอบ หรือข้ามคำถามส่วนที่ไม่บังคับได้โดยไม่มีผลกระทบใด ๆ ทั้งสิ้น แบบสำรวจนี้ไม่เก็บชื่อ-นามสกุล หมายเลขโทรศัพท์ เลขประจำตัวประชาชน หรืออีเมลของท่าน

' +
    'ผู้วิจัยและช่องทางติดต่อ: คณะผู้วิจัย สาขาวิชาคอมพิวเตอร์ธุรกิจและเทคโนโลยีดิจิทัล คณะวิทยาการจัดการ มหาวิทยาลัยราชภัฏยะลา (อาจารย์ที่ปรึกษา: อาจารย์นิมารูนี หะยีวาเงาะ อีเมล: nimarunee.h@yru.ac.th)'
  );

  // ตั้งค่าตามหลักจริยธรรมการวิจัยและ PDPA (ไม่เก็บอีเมล และไม่บังคับล็อกอิน)
  form.setCollectEmail(false);
  form.setLimitOneResponsePerUser(false);
  try {
    form.setRequireLogin(false);
  } catch (e) {
    Logger.log('หมายเหตุ: บัญชีองค์กรจำกัดการตั้งค่า RequireLogin อัตโนมัติ กรุณาติ๊กปิด "จำกัดเฉพาะผู้ใช้ในมหาวิทยาลัยราชภัฏยะลา" ในแท็บการตั้งค่าของฟอร์มอีกครั้ง');
  }

  form.setConfirmationMessage(
    'ขอขอบคุณที่สละเวลาร่วมตอบแบบสำรวจ ข้อมูลของท่านจะใช้เพื่อการศึกษาและนำเสนอในภาพรวมเท่านั้น'
  );

  // ส่วนที่ 1: คำถามคัดกรองและขอความยินยอม (SCR-01, SCR-02, CON-01)
  form.addSectionHeaderItem().setTitle('ส่วนที่ 1 การคัดกรองคุณสมบัติและการให้ความยินยอม');
  var qScr1 = form.addMultipleChoiceItem()
    .setTitle('คัดกรองข้อที่ 1: ท่านมีอายุ 18 ปีบริบูรณ์ขึ้นไปหรือไม่')
    .setRequired(true);

  var secScr2 = form.addPageBreakItem().setTitle('การคัดกรองคุณสมบัติ (ต่อ)');
  var qScr2 = form.addMultipleChoiceItem()
    .setTitle('คัดกรองข้อที่ 2: ขณะนี้ท่านกำลังมาเยี่ยมชมวัดคูหาภิมุข (วัดหน้าถ้ำ) เพื่อการท่องเที่ยวหรือเยี่ยมชมสถานที่ใช่หรือไม่')
    .setRequired(true);

  var secCon = form.addPageBreakItem().setTitle('การให้ความยินยอมเข้าร่วมการสำรวจ');
  var qCon = form.addMultipleChoiceItem()
    .setTitle('ท่านได้รับทราบคำชี้แจงข้างต้น และยินยอมเข้าร่วมการสำรวจนี้โดยสมัครใจหรือไม่')
    .setRequired(true);

  var secPart2 = form.addPageBreakItem()
    .setTitle('ส่วนที่ 2 ข้อมูลพื้นฐานของผู้ตอบแบบสำรวจ')
    .setHelpText('ข้อมูลส่วนนี้ใช้สำหรับจำแนกกลุ่มผู้ตอบในภาพรวม โดยทุกข้อมีตัวเลือก "ไม่ประสงค์ระบุ"');

  // ผูกเงื่อนไขข้ามหน้า (Skip Logic): หากตอบ ไม่ใช่ / ไม่ยินยอม ให้ส่งฟอร์มจบการสำรวจทันที
  qScr1.setChoices([
    qScr1.createChoice('ใช่', secScr2),
    qScr1.createChoice('ไม่ใช่', FormApp.PageNavigationType.SUBMIT)
  ]);
  qScr2.setChoices([
    qScr2.createChoice('ใช่', secCon),
    qScr2.createChoice('ไม่ใช่', FormApp.PageNavigationType.SUBMIT)
  ]);
  qCon.setChoices([
    qCon.createChoice('ยินยอม', secPart2),
    qCon.createChoice('ไม่ยินยอม', FormApp.PageNavigationType.SUBMIT)
  ]);

  // ส่วนที่ 2: คำถามพื้นฐาน (SUR-01 ถึง SUR-04) - จำเป็นต้องตอบ
  form.addMultipleChoiceItem()
    .setTitle('1. ช่วงอายุของท่าน')
    .setChoiceValues(['18–24 ปี', '25–34 ปี', '35–44 ปี', '45–54 ปี', '55 ปีขึ้นไป', 'ไม่ประสงค์ระบุ'])
    .setRequired(true);

  form.addMultipleChoiceItem()
    .setTitle('2. ปัจจุบันท่านอาศัยอยู่ในจังหวัดใดหรือประเทศใดเป็นหลัก')
    .setChoiceValues(['จังหวัดยะลา', 'จังหวัดปัตตานี', 'จังหวัดนราธิวาส', 'จังหวัดสงขลา', 'จังหวัดอื่นในประเทศไทย', 'ต่างประเทศ', 'ไม่ประสงค์ระบุ'])
    // ไม่เปิด "อื่น ๆ" เพราะมี 2 กลุ่ม (จังหวัดอื่น/ต่างประเทศ) แยกข้อความระบุไม่ได้
    .setRequired(true);

  form.addMultipleChoiceItem()
    .setTitle('3. ท่านมาเยี่ยมชมวัดคูหาภิมุข (วัดหน้าถ้ำ) ในครั้งนี้กับใครเป็นหลัก')
    .setChoiceValues(['เดินทางคนเดียว', 'ครอบครัว / เครือญาติ', 'เพื่อน', 'คู่รัก / คู่สมรส', 'คณะทัวร์ / หมู่คณะ', 'ไม่ประสงค์ระบุ'])
    .showOtherOption(true)
    .setRequired(true);

  form.addMultipleChoiceItem()
    .setTitle('4. พาหนะหลักที่ท่านใช้เดินทางมายังวัดคูหาภิมุข (วัดหน้าถ้ำ) ในครั้งนี้คือข้อใด')
    .setChoiceValues(['รถยนต์ส่วนตัว', 'รถจักรยานยนต์', 'รถโดยสารสาธารณะ', 'รถเช่า', 'รถนำเที่ยว / รถทัวร์', 'ไม่ประสงค์ระบุ'])
    .showOtherOption(true)
    .setRequired(true);

  // ส่วนที่ 3: ข้อมูลพฤติกรรมและความคิดเห็นเพิ่มเติม (SUR-05 ถึง SUR-11) - ไม่บังคับตอบ
  form.addPageBreakItem()
    .setTitle('ส่วนที่ 3 ข้อมูลพฤติกรรมและความคิดเห็นเพิ่มเติม (ไม่บังคับตอบ)')
    .setHelpText('ท่านสามารถเลือกตอบเฉพาะข้อที่สะดวกหรือข้ามได้ตามความสมัครใจ');

  form.addMultipleChoiceItem()
    .setTitle('5. วัตถุประสงค์หลักของการมาเยือนวัดคูหาภิมุข (วัดหน้าถ้ำ) ในครั้งนี้คืออะไร')
    .setChoiceValues(['ท่องเที่ยวเชิงศาสนาและวัฒนธรรม', 'ศึกษาประวัติศาสตร์และโบราณสถาน', 'พักผ่อนหรือถ่ายภาพ', 'แวะเยี่ยมชมระหว่างการเดินทาง'])
    .showOtherOption(true)
    .setRequired(false);

  form.addMultipleChoiceItem()
    .setTitle('6. ท่านรู้จักวัดคูหาภิมุข (วัดหน้าถ้ำ) จากช่องทางใดเป็นหลัก')
    .setChoiceValues(['สื่อสังคมออนไลน์ (เช่น Facebook / TikTok)', 'เว็บไซต์ / การค้นหาผ่าน Google', 'เพื่อนหรือครอบครัวแนะนำ', 'เคยมาเยือนสถานที่นี้มาก่อนแล้ว', 'ป้ายประชาสัมพันธ์ / สื่อประชาสัมพันธ์อื่น'])
    .showOtherOption(true)
    .setRequired(false);

  form.addMultipleChoiceItem()
    .setTitle('7. ค่าใช้จ่ายโดยประมาณต่อคนสำหรับการท่องเที่ยวในอำเภอเมืองยะลาครั้งนี้เป็นเท่าใด (นับรวมที่จ่ายแล้วและที่คาดว่าจะจ่ายตลอดทริปนี้ ไม่รวมค่าเดินทางมาจากภูมิลำเนาหรือต่างจังหวัด)')
    .setChoiceValues(['ไม่เกิน 300 บาท', '301–600 บาท', '601–1,000 บาท', '1,001–2,000 บาท', 'มากกว่า 2,000 บาท', 'ยังประเมินไม่ได้', 'ไม่ประสงค์ระบุ'])
    .setRequired(false);

  form.addCheckboxItem()
    .setTitle('8. ในการท่องเที่ยวอำเภอเมืองยะลาครั้งนี้ ท่านสนใจสินค้าและบริการประเภทใดบ้าง (เลือกได้มากกว่า 1 ข้อ)')
    .setHelpText('หากเลือก "ไม่มีความสนใจเป็นพิเศษ" โปรดไม่เลือกตัวเลือกอื่น')
    .setChoiceValues(['อาหารและเครื่องดื่ม', 'ของฝาก / ผลิตภัณฑ์ชุมชน', 'โรงแรม / ที่พัก / โฮมสเตย์', 'บริการเดินทาง / ขนส่ง', 'กิจกรรมท่องเที่ยว / นำเที่ยว', 'ไม่มีความสนใจเป็นพิเศษ'])
    .showOtherOption(true)
    .setRequired(false);

  form.addMultipleChoiceItem()
    .setTitle('9. โดยรวมแล้ว ท่านมีความพึงพอใจต่อการเยี่ยมชมวัดคูหาภิมุข (วัดหน้าถ้ำ) ในครั้งนี้ระดับใด')
    .setChoiceValues(['5 (มากที่สุด)', '4 (มาก)', '3 (ปานกลาง)', '2 (น้อย)', '1 (น้อยที่สุด)', 'ยังไม่สามารถประเมินได้'])
    .setRequired(false);

  form.addMultipleChoiceItem()
    .setTitle('10. หากมีโอกาส ท่านมีแนวโน้มจะกลับมาเยือนวัดคูหาภิมุข (วัดหน้าถ้ำ) อีกหรือไม่')
    .setChoiceValues(['ตั้งใจจะกลับมาอีก', 'อาจจะกลับมาอีก', 'ยังไม่แน่ใจ', 'ไม่น่าจะกลับมาอีก'])
    .setRequired(false);

  form.addParagraphTextItem()
    .setTitle('11. ท่านมีข้อเสนอแนะเพิ่มเติมเกี่ยวกับสินค้า บริการ หรือการจัดการท่องเที่ยวในพื้นที่อำเภอเมืองยะลาอย่างไรบ้าง')
    .setRequired(false);

  Logger.log('สร้างฟอร์มสำเร็จแล้ว!');
  Logger.log('ลิงก์สำหรับแก้ไขฟอร์ม: ' + form.getEditUrl());
  Logger.log('ลิงก์สำหรับผู้ตอบ (นำไปทำ QR Code): ' + form.getPublishedUrl());
}
